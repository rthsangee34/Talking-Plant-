/**
 * Get a random template for a condition
 */
export function getTamilTemplate(condition: keyof typeof TAMIL_TEMPLATES): string {
  const templates = TAMIL_TEMPLATES[condition];
  if (!templates || templates.length === 0) return TAMIL_TEMPLATES.fallback_no_data[0];
  return templates[Math.floor(Math.random() * templates.length)];
}
